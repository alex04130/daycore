package server

// Every user-visible error message this package produces, in one place.
//
// They used to be Chinese string literals inline at 279 call sites — perfectly
// readable, and completely untranslatable: adding a language is supposed to be
// dropping a JSON file into LOCALES_DIR, and none of these could be reached
// that way. Registering them here is what makes that claim true for the whole
// error surface.
//
// Only zh-CN is registered, deliberately. The catalog's fallback chain (exact →
// base language → default → any) means an en-US reader sees the Chinese today,
// which is exactly what they saw before — nothing regressed. What changed is
// that `i18n.Export("en-US")` now hands a translator a complete worklist, and
// `i18n.Coverage("en-US")` turns "how much is translated" into a number instead
// of a feeling. Authoring those strings is copy work and copy is frozen by
// project rule; the mechanism is not, and the mechanism is what this file is.
//
// Keys are derived from the handler they belong to, so a message in a bug
// report leads straight back to the code that produced it.


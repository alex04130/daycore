  let lang = 'zh-CN';
  try { lang = localStorage.getItem('daycore-lang') || 'zh-CN'; } catch (_) {}
  if (!dict[lang]) lang = 'zh-CN';
  const subs = new Set();

  function t(key, vars) {
    let s = (dict[lang] && dict[lang][key]);
    if (s === undefined) s = dict['zh-CN'][key];
    if (s === undefined) { console.warn('[i18n] missing key', key); return key; }
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]));
    return s;
  }

  function setLang(next) {
    if (!dict[next] || next === lang) return;
    lang = next;
    try { localStorage.setItem('daycore-lang', next); } catch (_) {}
    document.documentElement.lang = next;
    subs.forEach((fn) => fn(lang));
  }

  // ---- date & time formatting (always via Intl) ----
  const P = { // Intl option presets
    md:   { month: 'long', day: 'numeric' },
    mdw:  { month: 'long', day: 'numeric', weekday: 'short' },
    mdShort: { month: 'short', day: 'numeric' },
    w:    { weekday: 'short' },
    wNarrow: { weekday: 'narrow' },
    full: { year: 'numeric', month: 'long', day: 'numeric', weekday: 'long' },
    time: { hour: '2-digit', minute: '2-digit', hour12: false },
  };
  function toDate(d) {
    if (d instanceof Date) return d;
    const [a, b, c] = String(d).split('-').map(Number);
    return new Date(a, b - 1, c || 1);
  }
  function fmtDate(d, preset) {
    return new Intl.DateTimeFormat(lang, P[preset] || P.md).format(toDate(d));
  }
  function fmtTime(date) {
    return new Intl.DateTimeFormat(lang, P.time).format(date instanceof Date ? date : new Date(date));
  }
  // "今天 / 明天 / 7月9日 周四"
  function fmtDayLabel(dateStr, todayStr) {
    const diff = Math.round((toDate(dateStr) - toDate(todayStr)) / 864e5);
    if (diff === 0) return t('today');
    if (diff === 1) return t('tomorrow');
    return fmtDate(dateStr, 'mdw');
  }
  function weekdayNames(style) { // returns array indexed 0=Sunday…6=Saturday
    const base = new Date(2023, 0, 1); // a Sunday
    const f = new Intl.DateTimeFormat(lang, { weekday: style || 'short' });
    return Array.from({ length: 7 }, (_, i) => f.format(new Date(2023, 0, 1 + i)));
  }
  function joinWeekdays(byWeekday) {
    const names = weekdayNames(lang === 'zh-CN' ? 'narrow' : 'short');
    const sorted = [...byWeekday].sort((a, b) => a - b);
    const sep = lang === 'zh-CN' ? '、' : ', ';
    return sorted.map((i) => names[i]).join(sep);
  }

  return {
    t, setLang, _dict: dict,
    get lang() { return lang; },
    subscribe(fn) { subs.add(fn); return () => subs.delete(fn); },
    fmtDate, fmtTime, fmtDayLabel, weekdayNames, joinWeekdays, toDate,
  };
